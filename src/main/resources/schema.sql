CREATE SCHEMA app AUTHORIZATION museum_owner;

CREATE TABLE app.users
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(255) NOT NULL UNIQUE,
    full_name  VARCHAR(255) NOT NULL,
    email      VARCHAR(255) UNIQUE,
    created_at TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE app.exhibition_halls
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255)     NOT NULL UNIQUE,
    area       DOUBLE PRECISION NOT NULL CHECK (area > 0),
    available  BOOLEAN          NOT NULL DEFAULT true,
    created_at TIMESTAMP        NOT NULL DEFAULT now()
);

-- GOOD - можно выставлять, NEEDS_RESTORATION - нужна реставрация, IN_RESTORATION - сейчас на реставрации
CREATE TABLE app.exhibits
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(255)     NOT NULL,
    exhibit_condition VARCHAR(30)      NOT NULL DEFAULT 'GOOD'
        CHECK (exhibit_condition IN ('GOOD', 'NEEDS_RESTORATION', 'IN_RESTORATION')),
    required_area     DOUBLE PRECISION NOT NULL CHECK (required_area > 0),
    created_at        TIMESTAMP        NOT NULL DEFAULT now()
);

CREATE TABLE app.exhibitions
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    start_date DATE         NOT NULL,
    end_date   DATE         NOT NULL,
    status     VARCHAR(30)  NOT NULL DEFAULT 'PLANNED'
        CHECK (status IN ('PLANNED', 'OPEN', 'CLOSED', 'CANCELLED')),
    -- если куратора удалили, у выставки просто не будет куратора
    curator_id BIGINT REFERENCES app.users (id) ON DELETE SET NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT now(),
    CHECK (end_date >= start_date)
);

-- какой экспонат на какой выставке и в каком зале
CREATE TABLE app.exhibit_placements
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exhibit_id      BIGINT      NOT NULL REFERENCES app.exhibits (id) ON DELETE CASCADE,
    exhibition_id   BIGINT      NOT NULL REFERENCES app.exhibitions (id) ON DELETE CASCADE,
    hall_id         BIGINT      NOT NULL REFERENCES app.exhibition_halls (id) ON DELETE CASCADE,
    mounting_status VARCHAR(30) NOT NULL DEFAULT 'PLANNED'
        CHECK (mounting_status IN ('PLANNED', 'MOUNTED', 'DISMANTLED')),
    created_at      TIMESTAMP   NOT NULL DEFAULT now(),
    -- один экспонат нельзя два раза добавить на одну выставку
    UNIQUE (exhibit_id, exhibition_id)
);

-- сервису даю только работу с данными, менять таблицы он не может
GRANT USAGE ON SCHEMA app TO museum_service;
GRANT SELECT, INSERT, UPDATE, DELETE
    ON TABLE app.users, app.exhibition_halls, app.exhibits, app.exhibitions, app.exhibit_placements
    TO museum_service;
-- для id нужны последовательности
GRANT USAGE ON ALL SEQUENCES IN SCHEMA app TO museum_service;
